// Builds every icon variant from one geometry, so the launcher, themed, notification, Play and iOS
// icons always match.
//
//   node tools/store-assets/icon/build-icon.ts
//
// Writes SVGs to tools/store-assets/icon/out/ (rendered to PNG by ../render.sh) and the Android
// vector drawables straight into androidApp/src/main/res/.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { type Band, type Mark, circle, markGeometry, palette, svgMark } from '../shared/geometry.ts';

const here: string = dirname(fileURLToPath(import.meta.url));
const repo: string = join(here, '../../..');
const out: string = join(here, 'out');
const res: string = join(repo, 'androidApp/src/main/res');

// Adaptive icon space: 108×108; the launcher shows the middle 72×72 and masks keep a 66-wide circle.
const launcher: Mark = markGeometry({
  cx: 54,
  cy: 54,
  r: 26,
  wavelength: 1.15,
  gaps: [
    [0.1, 0.06, 0.05, 0.62],
    [0.4, 0.08, 0.055, 0.95],
    [0.69, 0.1, 0.06, 0.3],
  ],
});

// Notification: 24×24, two thick gaps so the slices survive at status-bar size.
const notification: Mark = markGeometry({
  cx: 12,
  cy: 12,
  r: 10,
  wavelength: 1.25,
  gaps: [
    [0.12, 0.17, 0.08, 0.62],
    [0.56, 0.2, 0.08, 0.95],
  ],
});

/** [x, y, radius, opacity] */
type Star = readonly [number, number, number, number];

const stars: ReadonlyArray<Star> = [
  [33, 32, 0.9, 0.55],
  [76, 29, 0.7, 0.4],
  [82, 44, 0.55, 0.3],
  [27, 47, 0.5, 0.25],
];

// ---------- SVG ----------

function svgBackground(): string {
  return `
  <defs>
    <linearGradient id="sky" x1="0" y1="0" x2="0" y2="108" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="${palette.skyTop}"/>
      <stop offset="1" stop-color="${palette.skyBottom}"/>
    </linearGradient>
    <radialGradient id="glow" cx="${launcher.cx}" cy="${launcher.cy}" r="44" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="${palette.glow}" stop-opacity="0.34"/>
      <stop offset="0.55" stop-color="${palette.glow}" stop-opacity="0.08"/>
      <stop offset="1" stop-color="${palette.glow}" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="108" height="108" fill="url(#sky)"/>
  <rect width="108" height="108" fill="url(#glow)"/>
  ${stars.map(([x, y, r, o]: Star): string => `<circle cx="${x}" cy="${y}" r="${r}" fill="${palette.star}" fill-opacity="${o}"/>`).join('\n  ')}`;
}

const svg = (size: number, body: string, viewBox: string = `0 0 ${size} ${size}`): string =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${size}" height="${size}">${body}</svg>\n`;

// ---------- Android VectorDrawable ----------

const vdHeader = (size: number, viewport: number, aapt: boolean): string =>
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/store-assets/icon/build-icon.ts; edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"${aapt ? '\n    xmlns:aapt="http://schemas.android.com/aapt"' : ''}
    android:width="${size}dp"
    android:height="${size}dp"
    android:viewportWidth="${viewport}"
    android:viewportHeight="${viewport}">
`;

const argb = (hex: string, opacity: number = 1): string =>
  `#${Math.round(opacity * 255).toString(16).padStart(2, '0').toUpperCase()}${hex.slice(1).toUpperCase()}`;

function vdMark(mark: Mark, mono?: string): string {
  const paths: string = mark.bands
    .map((b: Band, i: number): string => {
      if (mono) return `        <path android:fillColor="${mono}" android:pathData="${b.path}"/>`;
      const [a, z] = palette.layers[i];
      return `        <path android:pathData="${b.path}">
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="0" android:startY="${b.y0.toFixed(3)}" android:endX="0" android:endY="${b.y1.toFixed(3)}">
                    <item android:offset="0" android:color="${argb(a)}"/>
                    <item android:offset="1" android:color="${argb(z)}"/>
                </gradient>
            </aapt:attr>
        </path>`;
    })
    .join('\n');
  return `    <group>
        <clip-path android:pathData="${mark.clip}"/>
${paths}
    </group>
`;
}

function vdBackground(): string {
  const s: string = stars
    .map(([x, y, r, o]: Star): string => `    <path android:fillColor="${argb(palette.star, o)}" android:pathData="${circle(x, y, r)}"/>`)
    .join('\n');
  return `${vdHeader(108, 108, true)}    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="0" android:endY="108">
                <item android:offset="0" android:color="${argb(palette.skyTop)}"/>
                <item android:offset="1" android:color="${argb(palette.skyBottom)}"/>
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="${launcher.cx}" android:centerY="${launcher.cy}" android:gradientRadius="44">
                <item android:offset="0" android:color="${argb(palette.glow, 0.34)}"/>
                <item android:offset="0.55" android:color="${argb(palette.glow, 0.08)}"/>
                <item android:offset="1" android:color="${argb(palette.glow, 0)}"/>
            </gradient>
        </aapt:attr>
    </path>
${s}
</vector>
`;
}

// ---------- write ----------

function write(path: string, text: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

const bg: string = svgBackground();
const fg: string = svgMark(launcher, 'm');
// The full square icon (Play 512, iOS 1024): the adaptive icon's visible middle.
write(join(out, 'icon.svg'), svg(108, bg + fg, '18 18 72 72'));
// The mark alone on a transparent background (the iOS dark appearance).
write(join(out, 'mark.svg'), svg(108, fg, '18 18 72 72'));
write(join(out, 'mark-mono.svg'), svg(108, svgMark(launcher, 'm', '#FFFFFF'), '18 18 72 72'));
write(join(out, 'adaptive-background.svg'), svg(108, bg));
write(join(out, 'adaptive-foreground.svg'), svg(108, fg));
write(join(out, 'notification.svg'), svg(24, svgMark(notification, 'n', '#FFFFFF')));

write(join(res, 'drawable/ic_launcher_background.xml'), vdBackground());
write(join(res, 'drawable/ic_launcher_foreground.xml'), `${vdHeader(108, 108, true)}${vdMark(launcher)}</vector>\n`);
write(join(res, 'drawable/ic_launcher_monochrome.xml'), `${vdHeader(108, 108, false)}${vdMark(launcher, '#FFFFFFFF')}</vector>\n`);
write(join(res, 'drawable/ic_notification_small.xml'), `${vdHeader(24, 24, false)}${vdMark(notification, '#FFFFFFFF')}</vector>\n`);

console.log('icon: wrote', out, 'and the androidApp drawables');
